"""Private, loopback-only YOLO classification worker, managed by the Node API."""
import base64
import io
import os
import secrets
import tempfile
import threading
import time
from pathlib import Path

import numpy as np
import torch
from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import JSONResponse
from PIL import Image, UnidentifiedImageError
from ultralytics import YOLO

app = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)
models = {}
guard = threading.Lock()
compute = threading.Lock()
MAX_MODEL = 100 * 1024 * 1024
TTL = 30 * 60
torch.set_num_threads(max(1, min(4, os.cpu_count() or 1)))


@app.middleware('http')
async def authorize(request: Request, call_next):
    token = os.environ.get('TRAFFIC_AI_SECRET', '')
    if not token or not secrets.compare_digest(request.headers.get('x-ai-secret', ''), token):
        return JSONResponse({'message': 'Unauthorized worker request.'}, status_code=401)
    return await call_next(request)


def owner(request):
    value = request.headers.get('x-ai-owner')
    if not value:
        raise HTTPException(401, 'Missing owner')
    return value


def prune():
    expired = [key for key, item in models.items() if time.monotonic() - item['used'] > TTL]
    for key in expired:
        del models[key]


@app.get('/health')
def health():
    return {'status': 'ready', 'device': 'cpu', 'runtime': 'Ultralytics / PyTorch'}


@app.post('/model')
def load_model(request: Request, body: dict):
    account = owner(request)
    if not compute.acquire(blocking=False):
        raise HTTPException(429, 'Inference worker is busy. Try again shortly.')
    try:
        try:
            raw = base64.b64decode(body.get('data', ''), validate=True)
        except (ValueError, TypeError):
            raise HTTPException(400, 'Invalid model data.')
        if not raw or len(raw) > MAX_MODEL:
            raise HTTPException(413, 'Choose a .pt file up to 100 MB.')
        with guard:
            prune()
            if account not in models and len(models) >= 3:
                raise HTTPException(429, 'Worker model capacity reached. Release another session or wait 30 minutes.')
        # The temporary path is generated by us, never taken from an uploaded filename.
        with tempfile.TemporaryDirectory(prefix='traffic-classifier-') as directory:
            path = Path(directory) / 'uploaded.pt'
            path.write_bytes(raw)
            try:
                model = YOLO(str(path))
                if model.task != 'classify':
                    raise HTTPException(400, 'This is not a YOLO classification checkpoint. Choose a trained -cls / classification .pt model.')
                model.model.float().to('cpu').eval()
                labels = model.names
                size = model.overrides.get('imgsz', 224)
                if isinstance(size, (tuple, list)):
                    size = size[0]
                size = int(size) if isinstance(size, (int, float)) and 32 <= size <= 2048 else 224
            except HTTPException:
                raise
            except Exception as error:
                raise HTTPException(400, f'Unable to load YOLO classification checkpoint: {type(error).__name__}. Check the model and Ultralytics version.')
        with guard:
            identifier = secrets.token_hex(16)
            models[account] = {'id': identifier, 'model': model, 'labels': labels, 'used': time.monotonic()}
        return {'modelId': identifier, 'classes': len(labels), 'labels': list(labels.values()) if isinstance(labels, dict) else list(labels), 'width': size, 'height': size, 'device': 'cpu'}
    finally:
        compute.release()


@app.post('/release')
def release(request: Request, body: dict):
    with guard:
        item = models.get(owner(request))
        if item and item['id'] == body.get('modelId'):
            del models[owner(request)]
    return {'released': True}


@app.post('/classify')
def classify(request: Request, body: dict):
    width, height = body.get('width'), body.get('height')
    if type(width) is not int or type(height) is not int or not (32 <= width <= 2048 and 32 <= height <= 2048):
        raise HTTPException(400, 'Input width and height must be 32–2048 pixels.')
    if not compute.acquire(blocking=False):
        raise HTTPException(429, 'Inference worker is busy. Lower the inference rate or retry.')
    try:
        with guard:
            prune()
            item = models.get(owner(request))
            if not item or item['id'] != body.get('modelId'):
                raise HTTPException(410, 'Model expired or was replaced. Load it again.')
            item['used'] = time.monotonic()
        try:
            raw = base64.b64decode(body.get('frame', ''), validate=True)
            if len(raw) > 4 * 1024 * 1024:
                raise HTTPException(413, 'Frame too large.')
            image = Image.open(io.BytesIO(raw))
            if image.width != width or image.height != height:
                raise HTTPException(400, 'Frame resolution does not match the configured model input.')
            image = image.convert('RGB')
            pixels = np.asarray(image, dtype=np.float32) / 255.0
            tensor = torch.from_numpy(pixels.transpose(2, 0, 1).copy()).unsqueeze(0)
        except (ValueError, TypeError, UnidentifiedImageError, OSError):
            raise HTTPException(400, 'Invalid image frame.')
        started = time.perf_counter()
        try:
            # Tensor input bypasses Ultralytics' implicit image center crop, so the
            # exact user-selected ROI and rectangular resolution reach the network.
            with torch.inference_mode():
                output = item['model'].model(tensor)
                probabilities = output[0] if isinstance(output, (tuple, list)) else output
                probabilities = probabilities[0].float()
                if probabilities.ndim != 1 or probabilities.numel() != len(item['labels']) or not torch.isfinite(probabilities).all():
                    raise ValueError('Unexpected classification output')
                if (probabilities < 0).any() or abs(float(probabilities.sum()) - 1) > 0.01:
                    raise ValueError('Checkpoint must produce classification probabilities in evaluation mode')
                values, indices = probabilities.topk(min(5, probabilities.numel()))
                predictions = [{'classId': int(index), 'label': str(item['labels'][int(index)]), 'confidence': float(value)} for value, index in zip(values, indices)]
        except Exception as error:
            raise HTTPException(422, f'Model inference failed ({type(error).__name__}). Check the input resolution and checkpoint compatibility.')
        return {'predictions': predictions, 'inferenceMs': round((time.perf_counter() - started) * 1000, 1), 'width': width, 'height': height}
    finally:
        compute.release()
